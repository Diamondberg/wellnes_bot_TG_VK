#  Помощники
# ════════════════════════════════════════════════════════════
# Быстрый доступ к вопросу по номеру: QUESTIONS_BY_NUMBER[5]
QUESTIONS_BY_NUMBER: Dict[int, Question] = {q.number: q for q in QUESTIONS}

# Сколько вопросов на каждую систему — нужно для подсчёта процентов
QUESTIONS_PER_SYSTEM: Dict[str, int] = {}
for _q in QUESTIONS:
    for _sys in _q.systems:
        QUESTIONS_PER_SYSTEM[_sys] = QUESTIONS_PER_SYSTEM.get(_sys, 0) + 1


def total_questions() -> int:
    """Сколько всего вопросов в тесте."""
    return len(QUESTIONS)


def get_question(number: int) -> Question:
    """Получить вопрос по номеру (1..36)."""
    if number not in QUESTIONS_BY_NUMBER:
        raise ValueError(f"Неизвестный номер вопроса: {number}")
    return QUESTIONS_BY_NUMBER[number]


# ════════════════════════════════════════════════════════════
#  Самопроверка при импорте
# ════════════════════════════════════════════════════════════
# Если кто-то изменит вопросы и сломает структуру — упадём СРАЗУ при импорте,
# а не где-то в проде через неделю.
def _self_check() -> None:
    assert len(QUESTIONS) == 36, f"Должно быть 36 вопросов, а не {len(QUESTIONS)}"
    numbers = [q.number for q in QUESTIONS]
    assert numbers == list(range(1, 37)), "Номера вопросов должны идти 1..36 без пропусков"
    for q in QUESTIONS:
        assert q.systems, f"Вопрос {q.number} не привязан ни к одной системе"
        for sys_code in q.systems:
            assert sys_code in SYSTEMS, f"Вопрос {q.number} ссылается на неизвестную систему '{sys_code}'"


_self_check()
